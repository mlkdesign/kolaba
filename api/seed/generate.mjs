#!/usr/bin/env node
// Builds api/seed/seed.sql (git-ignored: it holds password hashes) from data.mjs.
//   node seed/generate.mjs [--check-media]      then: npx wrangler d1 execute kolaba-db --remote --file seed/seed.sql
// Idempotent: stable ids + INSERT OR IGNORE — running it twice adds nothing. Demo login passwords are created once
// in seed/.demo-credentials.json (git-ignored) and reused.
import { createHash, pbkdf2Sync, randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { businesses, creators, loginAccounts, pexels } from './data.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const APP_URL = 'https://mlkdesign.github.io/kolaba/';
const VERSION = 'web-mvp-01';
const NOW = Date.UTC(2026, 10, 8, 12, 0, 0); // fixed: identical SQL on every run
const DAY = 86_400_000;
const lines = [];
const emit = (s) => lines.push(s);
const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table, row) =>
  emit(`INSERT OR IGNORE INTO ${table} (${Object.keys(row).join(', ')}) VALUES (${Object.values(row).map(q).join(', ')});`);

// Deterministic randomness.
let state = 20261108;
const rand = () => { state |= 0; state = (state + 0x6d2b79f5) | 0; let t = Math.imul(state ^ (state >>> 15), 1 | state);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
const pick = (list) => list[Math.floor(rand() * list.length)];
const shuffle = (list) => list.map((x) => [rand(), x]).sort((a, b) => a[0] - b[0]).map((x) => x[1]);

// ─── Media URLs ───
const isPexels = (id) => Object.prototype.hasOwnProperty.call(pexels, id);
const video = (id) => isPexels(id)
  ? { url: pexels[id][0], poster: `${APP_URL}demo/posters/ReelPoster${id}.jpg`, provider: 'Pexels', license: 'Pexels License',
      attribution: pexels[id][1], title: pexels[id][2], duration: pexels[id][3], source: `https://www.pexels.com/video/${id}/` }
  : { url: `https://assets.mixkit.co/videos/${id}/${id}-720.mp4`, fallback: `https://assets.mixkit.co/videos/${id}/${id}-360.mp4`,
      poster: `https://assets.mixkit.co/videos/${id}/${id}-thumb-720-0.jpg`, provider: 'Mixkit',
      license: 'Mixkit Stock Video Free License', attribution: 'Mixkit', title: null, duration: null,
      source: `https://mixkit.co/free-stock-video/${id}/` };

if (process.argv.includes('--check-media')) {
  const ids = [...new Set(creators.flatMap((c) => c[10]))];
  const bad = [];
  for (const id of ids) {
    const v = video(id);
    for (const url of [v.url, v.poster]) {
      if (url.startsWith(APP_URL)) continue;
      const res = await fetch(url, { headers: { Range: 'bytes=0-1' } }).catch(() => null);
      if (!res || ![200, 206].includes(res.status)) bad.push(`${id} ${res?.status} ${url}`);
    }
  }
  console.log(`checked ${ids.length} videos (+ posters): ${bad.length ? bad.join('\n') : 'all reachable'}`);
  if (bad.length) process.exit(1);
}

// ─── Passwords (same scheme as src/lib/password.ts) ───
const credentialsPath = join(here, '.demo-credentials.json');
const credentials = existsSync(credentialsPath) ? JSON.parse(readFileSync(credentialsPath, 'utf8')) : {};
for (const account of loginAccounts) {
  credentials[account.email] ??= { password: randomBytes(12).toString('base64url'), salt: randomBytes(16).toString('base64') };
}
writeFileSync(credentialsPath, `${JSON.stringify(credentials, null, 2)}\n`, { mode: 0o600 });
const hash = (password, saltB64) => {
  let material = Buffer.from(password.normalize('NFKC'));
  for (let i = 0; i < 6; i++) material = pbkdf2Sync(material, Buffer.from(saltB64, 'base64'), 100_000, 32, 'sha256');
  return material.toString('base64');
};

